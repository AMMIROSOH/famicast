"""Write the interpreter's opcode switch body (runtime/cpu.c includes it).
Usage: python tools/gen_cpu_switch.py OUT.inc"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from recomp.c6502 import body  # noqa: E402
from recomp.ops import OPS  # noqa: E402

lines = ["/* generated by tools/gen_cpu_switch.py from recomp/ops.py; do not edit */"]
for op in OPS:
    lines.append(f"case 0x{op.code:02X}: {{ /* {op.mn} {op.mode} */")
    lines += ["    " + s for s in body(op) if s]
    lines.append("} break;")
os.makedirs(os.path.dirname(os.path.abspath(sys.argv[1])), exist_ok=True)
with open(sys.argv[1], "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
