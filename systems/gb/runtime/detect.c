/* The Game Boy and Game Boy Color, from the file's bytes (core/detect.h):
 * the Nintendo logo at $104, which the boot ROM compares, and the header
 * checksum at $14D, which it checks (Pan Docs "The Cartridge Header"). */
#include <string.h>

#include "detect.h"

static const uint8_t LOGO[48] = {
    0xCE, 0xED, 0x66, 0x66, 0xCC, 0x0D, 0x00, 0x0B, 0x03, 0x73, 0x00, 0x83, 0x00, 0x0C, 0x00, 0x0D,
    0x00, 0x08, 0x11, 0x1F, 0x88, 0x89, 0x00, 0x0E, 0xDC, 0xCC, 0x6E, 0xE6, 0xDD, 0xDD, 0xD9, 0x99,
    0xBB, 0xBB, 0x67, 0x63, 0x6E, 0x0E, 0xEC, 0xCC, 0xDD, 0xDC, 0x99, 0x9F, 0xBB, 0xB9, 0x33, 0x3E,
};

static int score(const uint8_t *d, size_t n) {
    if (n < 0x150 || memcmp(d + 0x104, LOGO, sizeof LOGO)) return 0;
    uint8_t x = 0;
    for (int i = 0x134; i <= 0x14C; i++) x = (uint8_t)(x - d[i] - 1);
    return x == d[0x14D] ? 100 : 70;  /* the logo alone: a hacked or damaged header */
}

const SystemDetector gb_detector = {"gb", "Game Boy / Game Boy Color", ".gb .gbc", score};
