"""Emit C for a recompiled program (docs/02 "Recompiled code").

One function per basic block. Each instruction is the interpreter's own code
for that opcode (recomp/c6502.py), so bus traffic and timing are identical
by construction; what the recompiler removes is fetch/decode/dispatch, and
with the address known, code bytes and PC values become constants
(static_body, M5b).
Every instruction start is an entry point (the switch at the top), so
execution can resume mid-block, e.g. after an RTI. After each instruction
the block returns if an interrupt is due, so interrupts are taken on the same
instruction as in the interpreter (this is what makes lockstep diffs exact).
"""
import re

from .c6502 import body

HEADER = """/* Generated by recomp (python -m recomp) from {rom}. Do not edit.
 * {nblocks} blocks, {ninstrs} instructions. PRG hash {prg_hash:08X}. */
#include "cpu_ops.h"
#include "recomp_rt.h"
"""


def fnv1a(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def disasm(ins, mem):
    raw = " ".join("%02X" % mem[(ins.pc + i) & 0xFFFF] for i in range(ins.size))
    mode, v = ins.op.mode, ins.operand
    arg = {"IMP": "", "ACC": "A", "IMM": f"#${v:02X}", "ZP": f"${v:02X}", "ZPX": f"${v:02X},X",
           "ZPY": f"${v:02X},Y", "ABS": f"${v:04X}", "ABX": f"${v:04X},X", "ABY": f"${v:04X},Y",
           "IND": f"(${v:04X})", "IZX": f"(${v:02X},X)", "IZY": f"(${v:02X}),Y",
           "REL": f"${ins.target:04X}" if ins.target is not None else ""}[mode]
    star = "" if ins.op.official else "*"
    return f"{ins.pc:04X}  {raw:<8}  {star}{ins.op.mn} {arg}".rstrip()


_PC_TOKEN = re.compile(r"rd\(c, c->pc\+\+\)|rd\(c, c->pc\)|c->pc(?! =)(?!\+\+)")


def static_body(ins, mem):
    """The interpreter's C for `ins`, rewritten for a known address: code
    fetches become fetch_k() with the ROM byte as a constant, and reads of
    c->pc become constants, up to the first assignment of a run-time value
    (RTS/RTI). c->pc is preset to the next instruction; control transfers
    overwrite it."""
    pc = (ins.pc + 1) & 0xFFFF
    lines = [f"c->pc = 0x{(ins.pc + ins.size) & 0xFFFF:04X};"]
    dynamic = False

    def sub(m):
        nonlocal pc
        tok = m.group(0)
        if tok == "c->pc":
            return f"0x{pc:04X}"
        k = f"fetch_k(c, 0x{pc:04X}, 0x{mem[pc]:02X})"
        if tok.endswith("++)"):
            pc = (pc + 1) & 0xFFFF
        return k

    for line in body(ins.op):
        if dynamic or not line:
            lines.append(line)
            continue
        lhs, sep, rhs = line.partition("c->pc = ")
        if sep and not lhs.strip():  # assignment: RHS sees the old value
            lines.append(lhs + sep + _PC_TOKEN.sub(sub, rhs))
            dynamic = lhs == ""  # top level (RTS/RTI); an indented one is a taken branch
        else:
            lines.append(_PC_TOKEN.sub(sub, line))
    return lines


def emit(blocks, mem, rom_name, prg_hash):
    out = [HEADER.format(rom=rom_name, nblocks=len(blocks),
                         ninstrs=sum(len(b.instrs) for b in blocks), prg_hash=prg_hash)]
    for blk in blocks:
        out.append(f"static void b_{blk.start:04X}(Cpu *c) {{")
        out.append("    switch (c->pc) {")
        out += [f"    case 0x{i.pc:04X}: goto i_{i.pc:04X};" for i in blk.instrs]
        out.append("    default: return;")
        out.append("    }")
        for ins in blk.instrs:
            out.append(f"i_{ins.pc:04X}: /* {disasm(ins, mem)} */")
            out.append(f"    fetch_k(c, 0x{ins.pc:04X}, 0x{mem[ins.pc]:02X});")
            out.append("    {")
            out += ["        " + s for s in static_body(ins, mem) if s]
            out.append("    }")
            if ins.op.mn == "KIL":
                out.append("    return;")
            elif ins is not blk.instrs[-1]:
                out.append("    if (c->poll_prev) return;")
        out.append("}")
        out.append("")

    # pc -> block function, for every instruction start in $8000-$FFFF
    out.append("static const RecompFn table[0x8000] = {")
    for blk in blocks:
        for ins in blk.instrs:
            if ins.pc >= 0x8000:
                out.append(f"    [0x{ins.pc - 0x8000:04X}] = b_{blk.start:04X},")
    out.append("};")
    out.append("")
    out.append("static RecompFn lookup(uint16_t pc) { return pc >= 0x8000 ? table[pc - 0x8000] : 0; }")
    out.append("")
    out.append("static const RecompProgram program = {")
    out.append(f"    0x{prg_hash:08X}u, \"{rom_name}\", lookup,")
    out.append("};")
    out.append("const RecompProgram *const recomp_program = &program;")
    return "\n".join(out) + "\n"
